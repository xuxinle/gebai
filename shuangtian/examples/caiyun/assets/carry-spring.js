// 裁云 · 弹簧驱动入场（参考 onetake 动作库的 spring 语感）
//
// ## 为什么必须用 JS 而不是给 JSON 加字段
//
// JSON 的 `enter` 是**单调缓动**（fade/rise/scale），永远不回头。
// 而"字标落定"好看的地方恰在**过冲再回弹**：从上方砸下来、略微压过头、
// 弹回原位。那是二阶响应——需要 ζ/ω 两个参数，且**没有预设终点时刻**
// （它自己决定何时停）。把这种动效做成 JSON 字段，会是"一种动效一个字段"，
// 无边界膨胀；脚本编排是通用通道：同一个 `spring()` 能驱动任何属性。
//
// ## 三条从实测学到的约束
//
// 1. **坐标是设计像素，不是比例**（`LayerDelta::dx` 直接加在设计坐标上）。
//    写 `canvas.w * 0.26` 是对的（它已经是像素），但不要以为传的是 0~1。
// 2. **只有 `dx/dy/dw/dh/scale/rotate/alpha` 七个量**——没有 `sx/sy`。
//    压扁只能靠 `scale` 整体缩放 + `dw/dh` 各向异性拉伸来近似。
//    写不存在的键**不会报错**（它只是被忽略），所以别凭想象写。
// 3. **`dw/dh` 是增量**，不是目标值；线从 0 宽长开就写 `dw = target * k`。

function layout(t, duration, canvas, layers) {
  const T_DROP = 0.12;   // 字标开始下落（秒）
  const T_LINE = 0.46;   // 落定线展开（晚于字标 ⇒ 二级动作）

  const out = [];

  // ── 字标：从上方落下，压过头再弹回 ──
  {
    const tau = t - T_DROP;
    // ζ=0.52 明显过冲、ω=17 中等速度。
    // 过冲是"有质量"的唯一来源：单调缓动再快也像"被推到位"。
    const k = spring(tau, 0.52, 17);
    // 落地瞬间速度最快 ⇒ 用速度把字号压小一点再弹回（近似 squash）。
    // 没有 `sy`，所以只能整体系数：`scale` 略减小 + 靠位移读速度。
    const vel = spring_vel(tau, 0.52, 17);
    const squash = 1 - Math.min(0.10, Math.abs(vel) * 0.008);
    out.push({
      dy: (1 - k) * -130,            // 从上方 130px 落下
      scale: (0.94 + 0.06 * k) * squash,
      alpha: tau <= 0 ? 0 : Math.min(1, tau * 7),
    });
  }

  // ── 落定线：从中心向两侧展开，稍晚起跳、几乎不过冲 ──
  {
    const tau = t - T_LINE;
    // ζ=0.86 干脆、ω=22 快：它只是"划一条线"，不跳舞。
    // **不同元素用不同的 ζ/ω**，是"不软"的关键——
    // 所有东西套同一条曲线，读起来就是同一种 S。
    const k = spring(tau, 0.86, 22);
    // ⚠ 用 `scale.x`（水平缩放）长开，**不要**用 `dw`。
    //
    // 实测踩到：`LayerDelta::dw` 是**增量**且会被 `max(0, ...)` 夹住，
    // 若 JSON 里的基准 `w` 写 `"0%"`，则 `0 + dw` 之后又被夹到 0——
    // 整条线永远不会出现，而且**不报错**。
    //
    // 所以：基准给足宽度（26%），用 `scale` 从 0 长到 1。
    // `scale < 1` 时按中心缩放，视觉上就是"从中间向两侧展开"。
    //
    // 只给 x 方向缩放：`LayerDelta` 没有 `sx/sy`，`scale` 是各向同性的，
    // 所以用很短的 `enter_dur` 配合高度上本来就细的矩形——
    // 纵向缩放在 3px 高的线上看不出来。
    out.push({
      scale: Math.max(0.001, k),
      alpha: tau <= 0 ? 0 : Math.min(1, tau * 9),
    });
  }

  return out;
}
