  "### 6.0 音效默认不加（新增纪律，踩过坑）",
  "",
  "**不要因为「模板有这一节」就填音效。** 默认策略是：**配乐 + 配音，零音效**。",
  "",
  "为什么（实测数据，不是口味问题）：裁云把 `audio.voice` 里的所有轨一视同仁地混音，",
  "**只对配乐做 ducking（压到 35%），对音效不做**。于是音效会与旁白直接抢响度：",
  "实测一条 `success` 音效峰值 −5.7dB / 均值 −17.5dB，比同时刻的旁白**还响 2.5dB**；",
  "`impact` 也基本持平。听感上就是「叮ー下把说话盖掉」。",
  "",
  "`tts_sfx` 的预设（success / ding / sparkle / riser / impact / whoosh）都是正弦与噪声合成，",
  "**音色偏电子玩具感**，与冷静的技术叙事天然不同频；`riser→impact→sparkle` 三件套",
  "是预告片套路，用在没有爆点的产品片上等于给不存在的爆点造势。",
  "",
  "**什么时候才加**（满足任一条，并且要写进剧本写明理由）：",
