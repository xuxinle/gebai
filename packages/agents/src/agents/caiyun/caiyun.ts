  "### 6.0.1 验片看什么数（`caiyun_verify` 的口径）",
  "",
  "**「慢」不是一个数能说清的**——它至少是两个正交量，混着看必然判反：",
  "",
  "| 量 | 口径 | 目标 | 异常时先改什么 |",
  "|---|---|---|---|",
  "| `static_ratio` 全片静止占比 | 帧差 <1.2 的帧对 / 帧对数 | <40% | 缩短**镜内**静止时长 |",
  "| `segment_static` 逐镜静止占比 | 同上，按片段区间聚合 | 单镜 <70% | 改那一镜（全片平均会掩盖它） |",
  "| `change_density` 变化密度 | 在动的帧对 / 秒 | >0.5/s | 与静止占比正交：多而碎 ≠ 不快 |",
  "| `bright_frame_ratio` 过亮帧 | 平均亮度 >180 的帧占比 | <20% | 暗场里嵌白底素材要做多层融合 |",
  "",
  "**判据随数走**：静止占比必须连着「帧差阈值」一起报。阈值一动，48% 能变 25% 也能变 60%——",
  "不给阈值的百分比无法复核，下一轮谁也说不清是真变好了还是口径变了。",
  "",
  "**逐镜是关键**：实测全片静止 48% 掩盖了引导页 **81%** 静止的真相，改时长改了半天没用，",
  "因为问题在镜内。`caiyun_verify` 会直接指出「最静一镜」是哪一镜、在哪个时间区间。",
